/// PWM levels for the targeted sweep (low, mid, high, max).
const PWM_LEVELS: &[u8] = &[40, 100, 180, 255];

/// Polling interval during sampling (ms).
const POLL_MS: u64 = 500;

/// Minimum temperature variance (°C²) to consider a coupling meaningful.
const MIN_TEMP_VARIANCE: f64 = 0.01;

/// Seconds to wait for stress to raise temps before sweeping.
const STRESS_WARMUP_SECS: u64 = 30;

/// Seconds to sample temps at each PWM level during stress.
const STRESS_SAMPLE_SECS: u64 = 5;

/// Try to write a PWM value; if the driver rejects it (EINVAL, common for GPU fans
/// that enforce a minimum), try progressively higher values. Returns the PWM actually set.
fn is_einval(e: &anyhow::Error) -> bool {
    let msg = format!("{:#}", e);
    msg.contains("Invalid argument")
}

fn write_pwm_safe(fan: &mut Fan, target: u8) -> Result<u8> {
    match fan.write_pwm(target) {
        Ok(()) => return Ok(target),
        Err(e) if is_einval(&e) => {}
        Err(e) => return Err(e),
    }
    for pwm in (target + 1)..=255 {
        match fan.write_pwm(pwm) {
            Ok(()) => {
                eprintln!(
                    "  (fan '{}' minimum PWM = {}, driver rejected {})",
                    fan.name, pwm, target
                );
                return Ok(pwm);
            }
            Err(e) if is_einval(&e) => {}
            Err(e) => return Err(e),
        }
    }
    anyhow::bail!("fan '{}': driver rejected all PWM values 0-255", fan.name)
}

// ─── Topology YAML ──────────────────────────────────────────────────────────

/// User-provided fan topology.
#[derive(serde::Deserialize)]
pub struct Topology {
    pub fans: Vec<FanTopo>,
}

/// A single fan header — may drive fans in multiple physical locations.
#[derive(serde::Deserialize)]
pub struct FanTopo {
    /// Must match a detected fan's auto_name
    pub name: String,
    /// Physical locations of fans on this header
    pub positions: Vec<FanPlacement>,
    /// Group name for coordinated control (e.g. "case")
    pub group: Option<String>,
}

#[derive(serde::Deserialize)]
pub struct FanPlacement {
    pub location: String,
    pub direction: String,
    /// Number of fans at this location (default 1)
    #[serde(default = "default_count")]
    pub count: u32,
}

fn default_count() -> u32 {
    1
}

pub fn load_topology(path: &Path) -> Result<Topology> {
    let content = std::fs::read_to_string(path)
        .with_context(|| format!("failed to read topology file: {}", path.display()))?;
    let topo: Topology = serde_yaml::from_str(&content)
        .with_context(|| format!("failed to parse topology YAML: {}", path.display()))?;
    anyhow::ensure!(!topo.fans.is_empty(), "topology file has no fan entries");
    Ok(topo)
}

/// Generate a topology YAML template from detection results.
/// Users edit this before running the benchmark.
pub fn generate_topology_template(result: &DetectionResult) -> String {
    let mut out = String::new();
    out.push_str("# Fan topology template — generated by sc-nixgen detect\n");
    out.push_str("# Edit positions/directions to match your case layout, then run:\n");
    out.push_str("#   sc-nixgen benchmark --topology this-file.yaml\n");
    out.push_str("#\n");
    out.push_str("# Detected sensors:\n");
    for s in &result.sensors {
        let label = s.label.as_deref().unwrap_or("");
        out.push_str(&format!(
            "#   {:<16} ({} temp{}) {:.0}°C  {}\n",
            s.auto_name, s.hwmon_chip, s.index, s.current_temp_c, label
        ));
    }
    out.push_str("#\n");
    out.push_str("# Positions: front, rear, top, bottom, side, cpu_cooler, gpu_cooler\n");
    out.push_str("# Directions: intake, exhaust\n");
    out.push_str("#\n");
    out.push_str("# Remove fans you don't want to control (e.g. firmware-controlled GPU fans).\n");
    out.push_str("# Fans in the same 'group' share benchmark data (only one is swept).\n");
    out.push_str("\nfans:\n");

    for f in &result.fans {
        let rpm_info = match f.current_rpm {
            Some(0) => " (0 RPM — stopped or phantom?)".to_string(),
            Some(r) => format!(" ({} RPM)", r),
            None => String::new(),
        };
        out.push_str(&format!("  # {}{}\n", f.auto_name, rpm_info));

        let is_gpu = sc_detect::classify_chip(&f.hwmon_chip) == sc_detect::ChipClass::GpuTemp;
        let (location, direction) = if is_gpu {
            ("gpu_cooler", "exhaust")
        } else {
            ("front", "intake") // safe default — user should edit
        };

        out.push_str(&format!("  - name: {}\n", f.auto_name));
        out.push_str("    positions:\n");
        out.push_str(&format!("      - location: {}\n", location));
        out.push_str(&format!("        direction: {}\n", direction));
        out.push('\n');
    }

    out
}

fn parse_position(s: &str) -> Result<FanPosition> {
    match s {
        "front" => Ok(FanPosition::Front),
        "rear" => Ok(FanPosition::Rear),
        "top" => Ok(FanPosition::Top),
        "bottom" => Ok(FanPosition::Bottom),
        "side" => Ok(FanPosition::Side),
        "cpu_cooler" => Ok(FanPosition::CpuCooler),
        "gpu_cooler" => Ok(FanPosition::GpuCooler),
        _ => anyhow::bail!(
            "unknown position: '{}' (expected: front, rear, top, bottom, side, cpu_cooler, gpu_cooler)",
            s
        ),
    }
}

fn parse_direction(s: &str) -> Result<AirflowDirection> {
    match s {
        "intake" => Ok(AirflowDirection::Intake),
        "exhaust" => Ok(AirflowDirection::Exhaust),
        _ => anyhow::bail!("unknown direction: '{}' (expected: intake, exhaust)", s),
    }
}

// ─── Fan classification ─────────────────────────────────────────────────────

#[derive(Debug, Clone, PartialEq)]
enum FanRole {
    DirectCooler,
    CaseRepresentative,
    CaseFollower { representative: String },
}

struct ClassifiedFan {
    name: String,
    role: FanRole,
}

type PreparedHardware = (Vec<Fan>, Vec<Sensor>, Vec<String>, Config);

fn classify_fans(topo: &Topology) -> Result<Vec<ClassifiedFan>> {
    let mut classified = Vec::new();
    let mut group_reps: std::collections::HashMap<String, String> =
        std::collections::HashMap::new();

    for ft in &topo.fans {
        if let Some(ref group) = ft.group {
            group_reps
                .entry(group.clone())
                .or_insert_with(|| ft.name.clone());
        }
    }

    for ft in &topo.fans {
        anyhow::ensure!(
            !ft.positions.is_empty(),
            "fan '{}' has no positions",
            ft.name
        );

        let primary = ft.positions.iter().max_by_key(|p| p.count).unwrap();
        let position = parse_position(&primary.location)?;
        let _direction = parse_direction(&primary.direction)?;

        let is_direct = matches!(position, FanPosition::CpuCooler | FanPosition::GpuCooler);

        let role = if is_direct {
            FanRole::DirectCooler
        } else if let Some(ref group) = ft.group {
            let rep = group_reps.get(group).unwrap();
            if *rep == ft.name {
                FanRole::CaseRepresentative
            } else {
                FanRole::CaseFollower {
                    representative: rep.clone(),
                }
            }
        } else {
            FanRole::CaseRepresentative
        };

        classified.push(ClassifiedFan {
            name: ft.name.clone(),
            role,
        });
    }

    Ok(classified)
}

// ─── Prepare from detection ─────────────────────────────────────────────────

pub fn prepare_from_detect(result: &DetectionResult, topo: &Topology) -> Result<PreparedHardware> {
    let instance_map = build_instance_map(result);

    let mut sensors = Vec::new();
    let mut sensor_names = Vec::new();
    let mut sensor_configs = Vec::new();

    for ds in &result.sensors {
        match Sensor::from_path(&ds.auto_name, &ds.hwmon_path, ds.index) {
            Ok(sensor) => {
                sensor_names.push(ds.auto_name.clone());
                sensors.push(sensor);
                sensor_configs.push(SensorConfig {
                    name: ds.auto_name.clone(),
                    hwmon: ds.hwmon_chip.clone(),
                    index: ds.index,
                    hwmon_instance: hwmon_instance_for(
                        &instance_map,
                        &ds.hwmon_chip,
                        &ds.hwmon_path,
                    ),
                });
            }
            Err(e) => eprintln!("skipping sensor '{}': {}", ds.auto_name, e),
        }
    }

    let mut fans = Vec::new();
    let mut fan_configs = Vec::new();

    for ft in &topo.fans {
        let detected = result.fans.iter().find(|df| df.auto_name == ft.name);
        let df = match detected {
            Some(df) => df,
            None => {
                let available: Vec<&str> =
                    result.fans.iter().map(|f| f.auto_name.as_str()).collect();
                anyhow::bail!(
                    "topology fan '{}' not found in detected hardware. Available: {:?}",
                    ft.name,
                    available
                );
            }
        };

        anyhow::ensure!(
            !ft.positions.is_empty(),
            "fan '{}' has no positions defined",
            ft.name
        );

        let primary = ft.positions.iter().max_by_key(|p| p.count).unwrap();
        let position = parse_position(&primary.location)?;
        let direction = parse_direction(&primary.direction)?;

        match Fan::from_path(&df.auto_name, &df.hwmon_path, df.pwm_index) {
            Ok(fan) => {
                fans.push(fan);
                fan_configs.push(FanConfig {
                    name: df.auto_name.clone(),
                    hwmon: df.hwmon_chip.clone(),
                    pwm_index: df.pwm_index,
                    hwmon_instance: hwmon_instance_for(
                        &instance_map,
                        &df.hwmon_chip,
                        &df.hwmon_path,
                    ),
                    topology: FanTopology {
                        position,
                        direction,
                        group: ft.group.clone(),
                    },
                    sensors: sensor_names.clone(),
                    curve: default_curve(),
                });
            }
            Err(e) => eprintln!("skipping fan '{}': {}", df.auto_name, e),
        }
    }

    if fans.is_empty() {
        anyhow::bail!("no fans resolved — cannot benchmark");
    }

    let config = Config {
        poll_interval_ms: 2000,
        derivative: DerivativeConfig {
            window_size: 10,
            boost_threshold: 2.0,
            decay_rate: 0.5,
        },
        sensors: sensor_configs,
        fans: fan_configs,
        tuning: Default::default(),
    };

    Ok((fans, sensors, sensor_names, config))
}

fn build_instance_map(
    result: &DetectionResult,
) -> std::collections::HashMap<String, Vec<std::path::PathBuf>> {
    let mut map: std::collections::HashMap<String, Vec<std::path::PathBuf>> =
        std::collections::HashMap::new();
    for chip in &result.chips {
        let paths = map.entry(chip.name.clone()).or_default();
        if !paths.contains(&chip.path) {
            paths.push(chip.path.clone());
        }
    }
    for paths in map.values_mut() {
        paths.sort();
    }
    map
}

fn hwmon_instance_for(
    map: &std::collections::HashMap<String, Vec<std::path::PathBuf>>,
    chip_name: &str,
    hwmon_path: &std::path::Path,
) -> Option<u32> {
    let paths = map.get(chip_name)?;
    if paths.len() <= 1 {
        return None;
    }
    paths.iter().position(|p| p == hwmon_path).map(|i| i as u32)
}

fn default_curve() -> Vec<CurvePoint> {
    vec![
        CurvePoint { temp: 40, pwm: 0 },
        CurvePoint { temp: 55, pwm: 60 },
        CurvePoint { temp: 65, pwm: 120 },
        CurvePoint { temp: 75, pwm: 180 },
        CurvePoint { temp: 85, pwm: 230 },
        CurvePoint { temp: 95, pwm: 255 },
    ]
}

// ─── Adaptive settle detection ──────────────────────────────────────────────

fn wait_for_settle(sensors: &[Sensor]) -> Vec<f64> {
    let min_secs = 5;
    let max_secs = 20;
    let alpha_fast = 0.3;
    let alpha_slow = 0.1;
    let convergence_threshold = 0.15;

    let n = sensors.len();
    let mut ewma_fast = vec![0.0f64; n];
    let mut ewma_slow = vec![0.0f64; n];
    let mut initialized = false;

    let start = std::time::Instant::now();

    loop {
        let elapsed = start.elapsed().as_secs();
        let temps: Vec<f64> = sensors
            .iter()
            .map(|s| s.read_temp_c().unwrap_or(0.0))
            .collect();

        if !initialized {
            ewma_fast = temps.clone();
            ewma_slow = temps.clone();
            initialized = true;
        } else {
            for i in 0..n {
                ewma_fast[i] = alpha_fast * temps[i] + (1.0 - alpha_fast) * ewma_fast[i];
                ewma_slow[i] = alpha_slow * temps[i] + (1.0 - alpha_slow) * ewma_slow[i];
            }
        }

        if elapsed >= min_secs {
            let max_diff = ewma_fast
                .iter()
                .zip(ewma_slow.iter())
                .map(|(f, s)| (f - s).abs())
                .fold(0.0f64, f64::max);

            if max_diff < convergence_threshold {
                return temps;
            }
        }

        if elapsed >= max_secs {
            return temps;
        }

        thread::sleep(Duration::from_millis(POLL_MS));
    }
}

/// Wait for temperatures to rise above threshold during stress warmup.
/// Returns once target sensors exceed `baseline + min_rise_c` or timeout.
fn wait_for_stress_warmup(
    sensors: &[Sensor],
    sensor_names: &[String],
    target_prefix: &str,
    baseline: &[f64],
    min_rise_c: f64,
) {
    let start = std::time::Instant::now();
    let timeout = Duration::from_secs(STRESS_WARMUP_SECS);

    loop {
        if start.elapsed() >= timeout {
            eprintln!("  warmup timeout ({}s)", STRESS_WARMUP_SECS);
            return;
        }

        let temps: Vec<f64> = sensors
            .iter()
            .map(|s| s.read_temp_c().unwrap_or(0.0))
            .collect();

        // Check if any target sensor has risen enough
        let mut max_rise = 0.0f64;
        for (i, name) in sensor_names.iter().enumerate() {
            if name.starts_with(target_prefix) {
                let rise = temps[i] - baseline[i];
                max_rise = max_rise.max(rise);
            }
        }

        if max_rise >= min_rise_c {
            eprintln!(
                "  target sensors up {:.1}°C in {:.0}s",
                max_rise,
                start.elapsed().as_secs_f64()
            );
            return;
        }

        thread::sleep(Duration::from_millis(POLL_MS));
    }
}

fn sample_temps(sensors: &[Sensor], duration_secs: u64) -> Vec<f64> {
    let n_samples = (duration_secs * 1000 / POLL_MS) as usize;
    let mut accumulators = vec![0.0f64; sensors.len()];

    for _ in 0..n_samples {
        for (j, sensor) in sensors.iter().enumerate() {
            if let Ok(temp) = sensor.read_temp_c() {
                accumulators[j] += temp;
            }
        }
        thread::sleep(Duration::from_millis(POLL_MS));
    }

    accumulators
        .iter()
        .map(|acc| acc / n_samples as f64)
        .collect()
}

// ─── Stall detection ────────────────────────────────────────────────────────

fn find_stall_threshold(fan: &mut Fan) -> Result<u8> {
    let mut lo: u8 = 0;
    let mut hi: u8 = 80;
    let mut stall_pwm: u8 = 0;

    let actual_hi = write_pwm_safe(fan, hi)?;
    thread::sleep(Duration::from_secs(3));
    let rpm = fan.read_rpm().unwrap_or(0);
    if rpm == 0 {
        return Ok(0);
    }

    lo = lo.max(actual_hi.saturating_sub(hi));

    while lo < hi {
        let mid = lo + (hi - lo) / 2;
        let actual = write_pwm_safe(fan, mid)?;
        thread::sleep(Duration::from_secs(2));
        let rpm = fan.read_rpm().unwrap_or(0);

        if rpm > 0 {
            stall_pwm = actual;
            hi = mid;
        } else {
            lo = mid + 1;
        }

        if hi - lo <= 3 {
            break;
        }
    }

    Ok(stall_pwm)
}

// ─── Benchmark ──────────────────────────────────────────────────────────────

/// Per-fan measurement data collected during a stress phase.
struct PhaseMeasurement {
    fan_name: String,
    /// For each PWM level: (pwm, per-sensor average temps)
    readings: Vec<(u8, Vec<f64>)>,
}

/// Run stress-based thermal coupling benchmark.
///
/// Protocol:
/// 1. Pre-flight: controllability check, stall detection
/// 2. CPU stress phase: built-in FP thread pool → sweep fans → measure CPU sensor coupling
/// 3. GPU stress phase: force max GPU clocks → sweep fans → measure GPU sensor coupling
/// 4. Compute coupling matrix from measurements
pub fn run_benchmark(
    fans: &mut [Fan],
    sensors: &[Sensor],
    sensor_names: &[String],
    topo: &Topology,
) -> Result<TuningResponse> {
    let classified = classify_fans(topo)?;
    let n_sweepable = classified
        .iter()
        .filter(|c| !matches!(c.role, FanRole::CaseFollower { .. }))
        .count();

    let has_cpu_sensors = sensor_names.iter().any(|s| s.starts_with("cpu"));
    let has_gpu_sensors = sensor_names.iter().any(|s| s.starts_with("gpu"));
    let n_phases = has_cpu_sensors as usize + has_gpu_sensors as usize;

    eprintln!(
        "Stress benchmark: {} fans ({} to sweep), {} sensors, {} stress phase(s)",
        fans.len(),
        n_sweepable,
        sensors.len(),
        n_phases,
    );

    let est_secs = 30
        + n_phases as u64
            * (STRESS_WARMUP_SECS + n_sweepable as u64 * PWM_LEVELS.len() as u64 * 12);
    eprintln!("Estimated duration: ~{} minutes", est_secs / 60 + 1);

    // ── Pre-flight: controllability check ───────────────────────────────────

    let mut controllable: Vec<bool> = Vec::new();
    for fan in fans.iter_mut() {
        if let Err(e) = fan.set_manual() {
            eprintln!(
                "  fan '{}': cannot set manual mode ({}), skipping",
                fan.name, e
            );
            controllable.push(false);
            continue;
        }
        match write_pwm_safe(fan, 128) {
            Ok(_) => controllable.push(true),
            Err(_) => {
                eprintln!(
                    "  fan '{}': driver rejects PWM writes, skipping (firmware-controlled?)",
                    fan.name
                );
                let _ = fan.restore_original();
                controllable.push(false);
            }
        }
    }

    let n_controllable = controllable.iter().filter(|&&c| c).count();
    if n_controllable == 0 {
        anyhow::bail!("no fans are controllable — cannot benchmark");
    }
    eprintln!("{}/{} fans controllable", n_controllable, fans.len());

    // ── Pre-flight: stall detection ─────────────────────────────────────────

    eprintln!("\n=== Stall detection ===");
    let mut stall_thresholds: std::collections::HashMap<String, u8> =
        std::collections::HashMap::new();
    for (fan, &is_ctrl) in fans.iter_mut().zip(controllable.iter()) {
        if !is_ctrl {
            eprintln!("  {} ... skipped (not controllable)", fan.name);
            continue;
        }
        eprint!("  {} ... ", fan.name);
        let stall = find_stall_threshold(fan)?;
        eprintln!("stall PWM = {}", stall);
        stall_thresholds.insert(fan.name.clone(), stall);
        write_pwm_safe(fan, 0)?;
    }

    // ── Idle baseline ───────────────────────────────────────────────────────

    eprintln!("\n=== Idle baseline (all fans max) ===");
    for (fan, &is_ctrl) in fans.iter_mut().zip(controllable.iter()) {
        if is_ctrl {
            write_pwm_safe(fan, 255)?;
        }
    }
    wait_for_settle(sensors);
    let baseline = sample_temps(sensors, 3);
    eprintln!("Baseline temperatures (full cooling):");
    for (i, name) in sensor_names.iter().enumerate() {
        eprintln!("  {} = {:.1}°C", name, baseline[i]);
    }

    // ── Stress phases ───────────────────────────────────────────────────────

    let mut all_measurements: Vec<PhaseMeasurement> = Vec::new();

    if has_cpu_sensors {
        eprintln!("\n=== CPU Stress Phase ===");
        let phase_measurements = run_stress_phase(
            fans,
            sensors,
            sensor_names,
            &classified,
            &controllable,
            &stall_thresholds,
            &baseline,
            "cpu",
            StressProcess::start_cpu,
        )?;
        all_measurements.extend(phase_measurements);
    }

    if has_gpu_sensors {
        eprintln!("\n=== GPU Stress Phase ===");
        let phase_measurements = run_stress_phase(
            fans,
            sensors,
            sensor_names,
            &classified,
            &controllable,
            &stall_thresholds,
            &baseline,
            "gpu",
            StressProcess::start_gpu,
        )?;
        all_measurements.extend(phase_measurements);
    }

    // ── Restore all fans ────────────────────────────────────────────────────

    eprintln!("\nRestoring fan control modes...");
    for (fan, &is_ctrl) in fans.iter().zip(controllable.iter()) {
        if is_ctrl {
            if let Err(e) = fan.restore_original() {
                eprintln!("  warning: failed to restore {}: {}", fan.name, e);
            }
        }
    }

    // ── Compute coupling matrix ─────────────────────────────────────────────

    let tuning = compute_tuning(&all_measurements, &classified, sensor_names);
    eprintln!(
        "\nBenchmark complete. {} coupling entries.",
        tuning.coupling_matrix.len()
    );

    Ok(tuning)
}

/// Run a single stress phase (CPU or GPU):
/// 1. Start stress workload
/// 2. Wait for target sensors to warm up
/// 3. Sweep each fan through PWM levels, measuring sensor temps
/// 4. Stop stress
#[allow(clippy::too_many_arguments)]
fn run_stress_phase<F>(
    fans: &mut [Fan],
    sensors: &[Sensor],
    sensor_names: &[String],
    classified: &[ClassifiedFan],
    controllable: &[bool],
    stall_thresholds: &std::collections::HashMap<String, u8>,
    baseline: &[f64],
    target_prefix: &str,
    start_stress: F,
) -> Result<Vec<PhaseMeasurement>>
where
    F: FnOnce() -> Result<StressProcess>,
{
    // Start stress workload
    let mut stress = start_stress()?;

    // Set all controllable fans to max during warmup so temps rise from workload, not fans
    for (fan, &is_ctrl) in fans.iter_mut().zip(controllable.iter()) {
        if is_ctrl {
            write_pwm_safe(fan, 255)?;
        }
    }

    // Wait for target temps to rise
    eprintln!("  Waiting for {} temps to rise...", target_prefix);
    wait_for_stress_warmup(sensors, sensor_names, target_prefix, baseline, 5.0);

    // Sample stressed baseline (at max fan speed)
    let stressed_baseline = sample_temps(sensors, 3);
    eprintln!("  Stressed temperatures (fans at max):");
    for (i, name) in sensor_names.iter().enumerate() {
        if name.starts_with(target_prefix) {
            eprintln!(
                "    {} = {:.1}°C (+{:.1}°C from idle)",
                name,
                stressed_baseline[i],
                stressed_baseline[i] - baseline[i]
            );
        }
    }

    // Sweep each fan while stress continues
    let mut measurements = Vec::new();

    for (fan_idx, cf) in classified.iter().enumerate() {
        if !controllable[fan_idx] {
            continue;
        }

        if let FanRole::CaseFollower { .. } = cf.role {
            continue;
        }

        eprintln!(
            "\n  --- Sweeping: {} ({:?}) under {} stress ---",
            cf.name, cf.role, target_prefix
        );

        // Set all OTHER fans to max cooling so only the swept fan's effect is measured
        for (i, fan) in fans.iter_mut().enumerate() {
            if i != fan_idx && controllable[i] {
                write_pwm_safe(fan, 255)?;
            }
        }

        let stall = *stall_thresholds.get(&cf.name).unwrap_or(&0);
        let mut readings = Vec::new();

        // Sweep from high to low PWM (start with max cooling, reduce to see temp rise)
        let effective_levels: Vec<u8> = {
            let mut levels: Vec<u8> = PWM_LEVELS.iter().copied().filter(|&p| p > stall).collect();
            // Add stall threshold as lowest level
            levels.insert(0, stall.max(1));
            // Sort descending: high PWM (max cooling) first
            levels.sort_unstable_by(|a, b| b.cmp(a));
            levels
        };

        for &pwm in &effective_levels {
            eprint!("    PWM={:>3} ... ", pwm);
            write_pwm_safe(&mut fans[fan_idx], pwm)?;

            // Shorter settle during stress — temps move faster under load
            wait_for_settle(sensors);

            let temps = sample_temps(sensors, STRESS_SAMPLE_SECS);

            // Print only target sensors
            let temp_str: Vec<String> = sensor_names
                .iter()
                .zip(temps.iter())
                .filter(|(name, _)| name.starts_with(target_prefix))
                .map(|(name, t)| format!("{}={:.1}°C", name, t))
                .collect();
            eprintln!("{}", temp_str.join(", "));

            readings.push((pwm, temps));
        }

        // Restore to max cooling before next fan
        write_pwm_safe(&mut fans[fan_idx], 255)?;

        measurements.push(PhaseMeasurement {
            fan_name: cf.name.clone(),
            readings,
        });
    }

    // Stop stress
    stress.stop();

    // Brief cooldown
    eprintln!("  Cooling down...");
    for (fan, &is_ctrl) in fans.iter_mut().zip(controllable.iter()) {
        if is_ctrl {
            write_pwm_safe(fan, 255)?;
        }
    }
    thread::sleep(Duration::from_secs(10));

    Ok(measurements)
}

/// Compute thermal coupling from stress benchmark measurements.
///
/// For each fan×sensor pair, fits a linear regression of temperature vs PWM.
/// Negative beta = fan cools that sensor. Positive beta = fan heats it.
/// Group followers inherit their representative's data.
fn compute_tuning(
    measurements: &[PhaseMeasurement],
    classified: &[ClassifiedFan],
    sensor_names: &[String],
) -> TuningResponse {
    let mut coupling_matrix = Vec::new();
    let mut step_responses = Vec::new();

    // Track best coupling per (fan, sensor) pair across phases
    let mut best_coupling: std::collections::HashMap<(String, String), (f64, f64)> =
        std::collections::HashMap::new();

    for measurement in measurements {
        for (sensor_idx, sensor_name) in sensor_names.iter().enumerate() {
            let readings: Vec<(f64, f64)> = measurement
                .readings
                .iter()
                .map(|(pwm, temps)| (*pwm as f64, temps[sensor_idx]))
                .collect();

            if readings.len() < 2 {
                continue;
            }

            let temps: Vec<f64> = readings.iter().map(|(_, t)| *t).collect();
            let t_mean = temps.iter().sum::<f64>() / temps.len() as f64;
            let variance =
                temps.iter().map(|t| (t - t_mean).powi(2)).sum::<f64>() / temps.len() as f64;
            if variance < MIN_TEMP_VARIANCE {
                continue;
            }

            let (slope, _intercept, r_squared) = linear_regression(&readings);
            let beta = slope * 10.0;

            let key = (measurement.fan_name.clone(), sensor_name.clone());

            // Keep the measurement with strongest |beta| and reasonable R²
            let dominated = best_coupling.get(&key).is_some_and(|(prev_beta, prev_r2)| {
                // Keep existing if it has stronger coupling with decent R²
                prev_beta.abs() > beta.abs() && *prev_r2 > 0.3
            });

            if !dominated {
                best_coupling.insert(key, (beta, r_squared));
            }
        }
    }

    // Convert best couplings to entries
    for ((fan_name, sensor_name), (beta, r_squared)) in &best_coupling {
        coupling_matrix.push(CouplingEntry {
            fan: fan_name.clone(),
            sensor: sensor_name.clone(),
            beta: *beta,
            r_squared: *r_squared,
        });

        step_responses.push(StepResponseEntry {
            fan: fan_name.clone(),
            sensor: sensor_name.clone(),
            gain_k: beta / 10.0,
            tau_ticks: 10.0,
            n_events: measurements
                .iter()
                .filter(|m| m.fan_name == *fan_name)
                .map(|m| m.readings.len())
                .sum(),
        });
    }

    // Propagate to group followers
    for cf in classified {
        if let FanRole::CaseFollower { ref representative } = cf.role {
            let rep_entries: Vec<CouplingEntry> = coupling_matrix
                .iter()
                .filter(|e| e.fan == *representative)
                .map(|e| CouplingEntry {
                    fan: cf.name.clone(),
                    sensor: e.sensor.clone(),
                    beta: e.beta,
                    r_squared: e.r_squared,
                })
                .collect();
            coupling_matrix.extend(rep_entries);

            let rep_steps: Vec<StepResponseEntry> = step_responses
                .iter()
                .filter(|e| e.fan == *representative)
                .map(|e| StepResponseEntry {
                    fan: cf.name.clone(),
                    sensor: e.sensor.clone(),
                    gain_k: e.gain_k,
                    tau_ticks: e.tau_ticks,
                    n_events: e.n_events,
                })
                .collect();
            step_responses.extend(rep_steps);
        }
    }

    TuningResponse {
        coupling_matrix,
        step_responses,
        cross_correlations: Vec::new(),
        thermal_integrals: Vec::new(),
    }
}

/// Simple linear regression: y = a + b*x. Returns (slope, intercept, r²).
fn linear_regression(data: &[(f64, f64)]) -> (f64, f64, f64) {
    let n = data.len() as f64;
    let sum_x: f64 = data.iter().map(|(x, _)| x).sum();
    let sum_y: f64 = data.iter().map(|(_, y)| y).sum();
    let sum_xx: f64 = data.iter().map(|(x, _)| x * x).sum();
    let sum_xy: f64 = data.iter().map(|(x, y)| x * y).sum();

    let denom = n * sum_xx - sum_x * sum_x;
    if denom.abs() < 1e-12 {
        return (0.0, sum_y / n, 0.0);
    }

    let slope = (n * sum_xy - sum_x * sum_y) / denom;
    let intercept = (sum_y - slope * sum_x) / n;

    let y_mean = sum_y / n;
    let ss_tot: f64 = data.iter().map(|(_, y)| (y - y_mean).powi(2)).sum();
    let ss_res: f64 = data
        .iter()
        .map(|(x, y)| {
            let predicted = intercept + slope * x;
            (y - predicted).powi(2)
        })
        .sum();
    let r_squared = if ss_tot > 1e-12 {
        1.0 - ss_res / ss_tot
    } else {
        0.0
    };

    (slope, intercept, r_squared)
}
