/// Polling interval during sampling (ms).
const POLL_MS: u64 = 500;

/// Settle detection: trailing window of samples used for the drift fit.
const SETTLE_WINDOW: usize = 40; // 20 s at POLL_MS
const SETTLE_MIN_SECS: f64 = 20.0;
/// Heatsink time constants are 30-120 s; give up well after that.
const SETTLE_MAX_SECS: f64 = 150.0;
/// Settled when the upper 95% bound of |drift| is below this (°C/min).
const SETTLE_MAX_DRIFT_C_PER_MIN: f64 = 0.5;

/// Seconds to wait for stress to raise temps before sweeping.
const STRESS_WARMUP_SECS: u64 = 30;

/// Seconds to sample temps at each PWM level during stress.
const STRESS_SAMPLE_SECS: u64 = 5;

/// Try to write a PWM value; if the driver rejects it (EINVAL, common for GPU fans
/// that enforce a minimum), try progressively higher values. Returns the PWM actually set.
fn is_einval(e: &anyhow::Error) -> bool {
    let msg = format!("{:#}", e);
    msg.contains("Invalid argument")
}

fn write_pwm_safe(fan: &mut Fan, target: u8) -> Result<u8> {
    match fan.write_pwm(target) {
        Ok(()) => return Ok(target),
        Err(e) if is_einval(&e) => {}
        Err(e) => return Err(e),
    }
    for pwm in (target + 1)..=255 {
        match fan.write_pwm(pwm) {
            Ok(()) => {
                eprintln!(
                    "  (fan '{}' minimum PWM = {}, driver rejected {})",
                    fan.name, pwm, target
                );
                return Ok(pwm);
            }
            Err(e) if is_einval(&e) => {}
            Err(e) => return Err(e),
        }
    }
    anyhow::bail!("fan '{}': driver rejected all PWM values 0-255", fan.name)
}

// ─── Topology Pkl ───────────────────────────────────────────────────────────

/// User-provided fan topology.
#[derive(Debug, serde::Deserialize)]
pub struct Topology {
    pub fans: Vec<FanTopo>,
}

/// A single fan header may drive fans in multiple physical locations.
#[derive(Debug, serde::Deserialize)]
pub struct FanTopo {
    /// Must match a detected fan's auto_name
    pub name: String,
    /// Physical locations of fans on this header
    pub positions: Vec<FanPlacement>,
    /// Group name for coordinated control (e.g. "case")
    pub group: Option<String>,
}

#[derive(Debug, serde::Deserialize)]
pub struct FanPlacement {
    pub location: String,
    pub direction: String,
    /// Number of fans at this location (default 1)
    #[serde(default = "default_count")]
    pub count: u32,
}

fn default_count() -> u32 {
    1
}

pub fn load_topology(path: &Path) -> Result<Topology> {
    let topo: Topology = sc_core::config::load_pkl(path)
        .with_context(|| format!("failed to evaluate topology Pkl {}", path.display()))?;
    anyhow::ensure!(!topo.fans.is_empty(), "topology file has no fan entries");
    Ok(topo)
}

/// Generate a topology Pkl template from detection results.
/// Users edit this before running the benchmark.
pub fn generate_topology_template(result: &DetectionResult) -> String {
    let mut out = String::new();
    out.push_str("// Fan topology template - generated by sc-nixgen detect\n");
    out.push_str("// Edit positions/directions to match your case layout, then run:\n");
    out.push_str("//   sc-nixgen benchmark --topology this-file.pkl\n");
    out.push_str("//\n");
    out.push_str("// Detected sensors:\n");
    for s in &result.sensors {
        let label = s.label.as_deref().unwrap_or("");
        out.push_str(&format!(
            "//   {:<16} ({} temp{}) {:.0} C  {}\n",
            s.auto_name, s.hwmon_chip, s.index, s.current_temp_c, label
        ));
    }
    out.push_str("//\n");
    out.push_str("// Positions: front, rear, top, bottom, side, cpu_cooler, gpu_cooler\n");
    out.push_str("// Directions: intake, exhaust\n");
    out.push_str("//\n");
    out.push_str("// Remove fans you don't want to control (e.g. firmware-controlled GPU fans).\n");
    out.push_str("// Fans in the same 'group' share benchmark data (only one is swept).\n");
    out.push_str("\nfans = new Listing {\n");

    for f in &result.fans {
        let rpm_info = match f.current_rpm {
            Some(0) => " (0 RPM - stopped or phantom?)".to_string(),
            Some(r) => format!(" ({} RPM)", r),
            None => String::new(),
        };
        out.push_str(&format!("  // {}{}\n", f.auto_name, rpm_info));

        let is_gpu = sc_detect::classify_chip(&f.hwmon_chip) == sc_detect::ChipClass::GpuTemp;
        let (location, direction) = if is_gpu {
            ("gpu_cooler", "exhaust")
        } else {
            ("front", "intake") // safe default — user should edit
        };

        out.push_str("  new {\n");
        out.push_str(&format!(
            "    name = {}\n",
            pklx::pkl_string_literal(&f.auto_name)
        ));
        out.push_str("    positions = new Listing {\n");
        out.push_str("      new {\n");
        out.push_str(&format!(
            "        location = {}\n",
            pklx::pkl_string_literal(location)
        ));
        out.push_str(&format!(
            "        direction = {}\n",
            pklx::pkl_string_literal(direction)
        ));
        out.push_str("      }\n");
        out.push_str("    }\n");
        out.push_str("  }\n\n");
    }

    out.push_str("}\n");
    out
}

