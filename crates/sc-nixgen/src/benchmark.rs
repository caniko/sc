fn parse_position(s: &str) -> Result<FanPosition> {
    match s {
        "front" => Ok(FanPosition::Front),
        "rear" => Ok(FanPosition::Rear),
        "top" => Ok(FanPosition::Top),
        "bottom" => Ok(FanPosition::Bottom),
        "side" => Ok(FanPosition::Side),
        "cpu_cooler" => Ok(FanPosition::CpuCooler),
        "gpu_cooler" => Ok(FanPosition::GpuCooler),
        _ => anyhow::bail!(
            "unknown position: '{}' (expected: front, rear, top, bottom, side, cpu_cooler, gpu_cooler)",
            s
        ),
    }
}

fn parse_direction(s: &str) -> Result<AirflowDirection> {
    match s {
        "intake" => Ok(AirflowDirection::Intake),
        "exhaust" => Ok(AirflowDirection::Exhaust),
        _ => anyhow::bail!("unknown direction: '{}' (expected: intake, exhaust)", s),
    }
}

// ─── Fan classification ─────────────────────────────────────────────────────

#[derive(Debug, Clone, PartialEq)]
enum FanRole {
    DirectCooler,
    CaseRepresentative,
    CaseFollower { representative: String },
}

struct ClassifiedFan {
    name: String,
    role: FanRole,
}

type PreparedHardware = (Vec<Fan>, Vec<Sensor>, Vec<String>, Config);

fn classify_fans(topo: &Topology) -> Result<Vec<ClassifiedFan>> {
    let mut classified = Vec::new();
    let mut group_reps: std::collections::HashMap<String, String> =
        std::collections::HashMap::new();

    for ft in &topo.fans {
        if let Some(ref group) = ft.group {
            group_reps
                .entry(group.clone())
                .or_insert_with(|| ft.name.clone());
        }
    }

    for ft in &topo.fans {
        anyhow::ensure!(
            !ft.positions.is_empty(),
            "fan '{}' has no positions",
            ft.name
        );

        let primary = ft.positions.iter().max_by_key(|p| p.count).unwrap();
        let position = parse_position(&primary.location)?;
        let _direction = parse_direction(&primary.direction)?;

        let is_direct = matches!(position, FanPosition::CpuCooler | FanPosition::GpuCooler);

        let role = if is_direct {
            FanRole::DirectCooler
        } else if let Some(ref group) = ft.group {
            let rep = group_reps.get(group).unwrap();
            if *rep == ft.name {
                FanRole::CaseRepresentative
            } else {
                FanRole::CaseFollower {
                    representative: rep.clone(),
                }
            }
        } else {
            FanRole::CaseRepresentative
        };

        classified.push(ClassifiedFan {
            name: ft.name.clone(),
            role,
        });
    }

    Ok(classified)
}

// ─── Prepare from detection ─────────────────────────────────────────────────

pub fn prepare_from_detect(result: &DetectionResult, topo: &Topology) -> Result<PreparedHardware> {
    let instance_map = build_instance_map(result);

    let mut sensors = Vec::new();
    let mut sensor_names = Vec::new();
    let mut sensor_configs = Vec::new();

    for ds in &result.sensors {
        match Sensor::from_path(&ds.auto_name, &ds.hwmon_path, ds.index) {
            Ok(sensor) => {
                sensor_names.push(ds.auto_name.clone());
                sensors.push(sensor);
                sensor_configs.push(SensorConfig {
                    name: ds.auto_name.clone(),
                    hwmon: ds.hwmon_chip.clone(),
                    index: ds.index,
                    hwmon_instance: hwmon_instance_for(
                        &instance_map,
                        &ds.hwmon_chip,
                        &ds.hwmon_path,
                    ),
                });
            }
            Err(e) => eprintln!("skipping sensor '{}': {}", ds.auto_name, e),
        }
    }

    let mut fans = Vec::new();
    let mut fan_configs = Vec::new();

    for ft in &topo.fans {
        let detected = result.fans.iter().find(|df| df.auto_name == ft.name);
        let df = match detected {
            Some(df) => df,
            None => {
                let available: Vec<&str> =
                    result.fans.iter().map(|f| f.auto_name.as_str()).collect();
                anyhow::bail!(
                    "topology fan '{}' not found in detected hardware. Available: {:?}",
                    ft.name,
                    available
                );
            }
        };

        anyhow::ensure!(
            !ft.positions.is_empty(),
            "fan '{}' has no positions defined",
            ft.name
        );

        let primary = ft.positions.iter().max_by_key(|p| p.count).unwrap();
        let position = parse_position(&primary.location)?;
        let direction = parse_direction(&primary.direction)?;

        match Fan::from_path(&df.auto_name, &df.hwmon_path, df.pwm_index) {
            Ok(fan) => {
                fans.push(fan);
                fan_configs.push(FanConfig {
                    name: df.auto_name.clone(),
                    hwmon: df.hwmon_chip.clone(),
                    pwm_index: df.pwm_index,
                    hwmon_instance: hwmon_instance_for(
                        &instance_map,
                        &df.hwmon_chip,
                        &df.hwmon_path,
                    ),
                    topology: FanTopology {
                        position,
                        direction,
                        group: ft.group.clone(),
                    },
                    sensors: sensor_names.clone(),
                    curve: default_curve(),
                });
            }
            Err(e) => eprintln!("skipping fan '{}': {}", df.auto_name, e),
        }
    }

    if fans.is_empty() {
        anyhow::bail!("no fans resolved — cannot benchmark");
    }

    let config = Config {
        poll_interval_ms: 2000,
        derivative: DerivativeConfig {
            window_size: 10,
            boost_threshold: 2.0,
            decay_rate: 0.5,
        },
        sensors: sensor_configs,
        fans: fan_configs,
        nvidia: vec![],
        tuning: Default::default(),
    };

    Ok((fans, sensors, sensor_names, config))
}

fn build_instance_map(
    result: &DetectionResult,
) -> std::collections::HashMap<String, Vec<std::path::PathBuf>> {
    let mut map: std::collections::HashMap<String, Vec<std::path::PathBuf>> =
        std::collections::HashMap::new();
    for chip in &result.chips {
        let paths = map.entry(chip.name.clone()).or_default();
        if !paths.contains(&chip.path) {
            paths.push(chip.path.clone());
        }
    }
    for paths in map.values_mut() {
        paths.sort();
    }
    map
}

fn hwmon_instance_for(
    map: &std::collections::HashMap<String, Vec<std::path::PathBuf>>,
    chip_name: &str,
    hwmon_path: &std::path::Path,
) -> Option<u32> {
    let paths = map.get(chip_name)?;
    if paths.len() <= 1 {
        return None;
    }
    paths.iter().position(|p| p == hwmon_path).map(|i| i as u32)
}

fn default_curve() -> Vec<CurvePoint> {
    vec![
        CurvePoint { temp: 40, pwm: 0 },
        CurvePoint { temp: 55, pwm: 60 },
        CurvePoint { temp: 65, pwm: 120 },
        CurvePoint { temp: 75, pwm: 180 },
        CurvePoint { temp: 85, pwm: 230 },
        CurvePoint { temp: 95, pwm: 255 },
    ]
}

// ─── Adaptive settle detection ──────────────────────────────────────────────

/// Wait until every watched sensor has stopped drifting.
///
/// Fits an OLS line to the trailing `SETTLE_WINDOW` samples of each watched
/// sensor and declares it settled once `|slope| + t·SE(slope)` is below
/// `SETTLE_MAX_DRIFT_C_PER_MIN`, i.e. a drift is statistically excluded
/// rather than merely unobserved in short-horizon noise.
fn wait_for_settle(sensors: &[Sensor], watch: &[bool], interrupt: &InterruptGuard) -> Result<()> {
    let start = std::time::Instant::now();
    let mut history: Vec<std::collections::VecDeque<(f64, f64)>> =
        vec![std::collections::VecDeque::with_capacity(SETTLE_WINDOW); sensors.len()];

    loop {
        interrupt.check()?;
        let elapsed = start.elapsed().as_secs_f64();
        for (h, temp) in history.iter_mut().zip(read_temperatures(sensors)?) {
            if h.len() == SETTLE_WINDOW {
                h.pop_front();
            }
            h.push_back((elapsed, temp));
        }

        if elapsed >= SETTLE_MIN_SECS
            && history
                .iter()
                .zip(watch)
                .filter(|(_, w)| **w)
                .all(|(h, _)| drift_upper_bound(h) < SETTLE_MAX_DRIFT_C_PER_MIN / 60.0)
        {
            return Ok(());
        }
        if elapsed >= SETTLE_MAX_SECS {
            eprint!("(still drifting after {:.0}s) ", SETTLE_MAX_SECS);
            return Ok(());
        }

        interrupt.sleep(Duration::from_millis(POLL_MS))?;
    }
}

/// Upper 95% confidence bound of |dT/dt| (°C/s) for a series of (t, temp).
fn drift_upper_bound(samples: &std::collections::VecDeque<(f64, f64)>) -> f64 {
    let x: Vec<Vec<f64>> = samples.iter().map(|(t, _)| vec![1.0, *t]).collect();
    let y: Vec<f64> = samples.iter().map(|(_, temp)| *temp).collect();
    match ols(&x, &y) {
        Some(fit) => fit.coef[1].abs() + t_critical_95(fit.dof) * fit.se[1],
        None => f64::INFINITY,
    }
}

/// Wait for temperatures to rise above threshold during stress warmup.
/// Returns once target sensors exceed `baseline + min_rise_c` or timeout.
fn wait_for_stress_warmup(
    sensors: &[Sensor],
    sensor_names: &[String],
    target_prefix: &str,
    baseline: &[f64],
    min_rise_c: f64,
    interrupt: &InterruptGuard,
) -> Result<()> {
    let start = std::time::Instant::now();
    let timeout = Duration::from_secs(STRESS_WARMUP_SECS);

    loop {
        interrupt.check()?;
        if start.elapsed() >= timeout {
            eprintln!("  warmup timeout ({}s)", STRESS_WARMUP_SECS);
            return Ok(());
        }

        let temps = read_temperatures(sensors)?;

        // Check if any target sensor has risen enough
        let mut max_rise = 0.0f64;
        for (i, name) in sensor_names.iter().enumerate() {
            if name.starts_with(target_prefix) {
                let rise = temps[i] - baseline[i];
                max_rise = max_rise.max(rise);
            }
        }

        if max_rise >= min_rise_c {
            eprintln!(
                "  target sensors up {:.1}°C in {:.0}s",
                max_rise,
                start.elapsed().as_secs_f64()
            );
            return Ok(());
        }

        interrupt.sleep(Duration::from_millis(POLL_MS))?;
    }
}

fn sample_temps(
    sensors: &[Sensor],
    duration_secs: u64,
    interrupt: &InterruptGuard,
) -> Result<Vec<f64>> {
    let n_samples = (duration_secs * 1000 / POLL_MS) as usize;
    let mut accumulators = vec![0.0f64; sensors.len()];

    for _ in 0..n_samples {
        interrupt.check()?;
        for (j, sensor) in sensors.iter().enumerate() {
            accumulators[j] += sensor
                .read_temp_c()
                .with_context(|| format!("failed to read sensor '{}'", sensor.name))?;
        }
        interrupt.sleep(Duration::from_millis(POLL_MS))?;
    }

    Ok(accumulators
        .iter()
        .map(|acc| acc / n_samples as f64)
        .collect())
}

fn read_temperatures(sensors: &[Sensor]) -> Result<Vec<f64>> {
    sensors
        .iter()
        .map(|sensor| {
            sensor
                .read_temp_c()
                .with_context(|| format!("failed to read sensor '{}'", sensor.name))
        })
        .collect()
}

// ─── Stall detection ────────────────────────────────────────────────────────

fn find_stall_threshold(fan: &mut Fan, interrupt: &InterruptGuard) -> Result<u8> {
    let mut lo: u8 = 0;
    let mut hi: u8 = 80;
    let mut stall_pwm: u8 = 0;

    let actual_hi = write_pwm_safe(fan, hi)?;
    interrupt.sleep(Duration::from_secs(3))?;
    let rpm = fan.read_rpm().unwrap_or(0);
    if rpm == 0 {
        return Ok(0);
    }

    lo = lo.max(actual_hi.saturating_sub(hi));

    while lo < hi {
        let mid = lo + (hi - lo) / 2;
        let actual = write_pwm_safe(fan, mid)?;
        interrupt.sleep(Duration::from_secs(2))?;
        let rpm = fan.read_rpm().unwrap_or(0);

        if rpm > 0 {
            stall_pwm = actual;
            hi = mid;
        } else {
            lo = mid + 1;
        }

        if hi - lo <= 3 {
            break;
        }
    }

    Ok(stall_pwm)
}

// ─── Benchmark ──────────────────────────────────────────────────────────────

/// Per-fan measurement data collected during a stress phase.
struct PhaseMeasurement {
    fan_name: String,
    /// For each PWM level: (pwm, seconds since sweep start, per-sensor average temps)
    readings: Vec<(u8, f64, Vec<f64>)>,
}

/// Order sweep levels so PWM is not monotone in time, then repeat the first
/// (highest) level at the end.
///
/// A monotone high→low sweep makes PWM perfectly collinear with elapsed time,
/// so any residual heat soak is attributed to the fan. Alternating extremes
/// plus a repeated reference make a linear drift term identifiable.
fn sweep_order(mut levels: Vec<u8>) -> Vec<u8> {
    levels.sort_unstable_by(|a, b| b.cmp(a));
    levels.dedup();
    let mut order = Vec::with_capacity(levels.len() + 1);
    let (mut lo, mut hi) = (0, levels.len());
    while lo < hi {
        order.push(levels[lo]);
        lo += 1;
        if lo < hi {
            hi -= 1;
            order.push(levels[hi]);
        }
    }
    if let Some(&first) = order.first() {
        order.push(first);
    }
    order
}

/// Run stress-based thermal coupling benchmark.
///
/// Protocol:
/// 1. Pre-flight: controllability check, stall detection
/// 2. CPU stress phase: built-in FP thread pool → sweep fans → measure CPU sensor coupling
/// 3. GPU stress phase: force max GPU clocks → sweep fans → measure GPU sensor coupling
/// 4. Compute coupling matrix from measurements
pub fn run_benchmark(
    fans: &mut [Fan],
    sensors: &[Sensor],
    sensor_names: &[String],
    topo: &Topology,
) -> Result<(TuningResponse, Vec<String>)> {
    let interrupt = InterruptGuard::new()?;
    // Keep the guard alive for the complete benchmark.  Every PWM write and
    // every early-return path is therefore followed by restoration of the
    // original PWM and enable mode.
    let mut control = FanControlGuard::new(fans);
    let fans = control.fans_mut();

    let classified = classify_fans(topo)?;
    let n_sweepable = classified
        .iter()
        .filter(|c| !matches!(c.role, FanRole::CaseFollower { .. }))
        .count();

    let has_cpu_sensors = sensor_names.iter().any(|s| s.starts_with("cpu"));
    let has_gpu_sensors = sensor_names.iter().any(|s| s.starts_with("gpu"));
    let n_phases = has_cpu_sensors as usize + has_gpu_sensors as usize;

    eprintln!(
        "Stress benchmark: {} fans ({} to sweep), {} sensors, {} stress phase(s)",
        fans.len(),
        n_sweepable,
        sensors.len(),
        n_phases,
    );

    // Per level: settle (SETTLE_MIN_SECS..SETTLE_MAX_SECS) + sample; levels =
    // PWM_LEVELS + stall level + the repeated reference level.
    let levels = PWM_LEVELS.len() as u64 + 2;
    let per_level = |settle: f64| settle as u64 + STRESS_SAMPLE_SECS;
    let est = |settle: f64| {
        30 + n_phases as u64
            * (STRESS_WARMUP_SECS + n_sweepable as u64 * levels * per_level(settle))
    };
    eprintln!(
        "Estimated duration: {}-{} minutes",
        est(SETTLE_MIN_SECS) / 60 + 1,
        est(SETTLE_MAX_SECS) / 60 + 1
    );

    // ── Pre-flight: controllability check ───────────────────────────────────

    let mut controllable: Vec<bool> = Vec::new();
    for fan in fans.iter_mut() {
        interrupt.check()?;
        if let Err(e) = fan.set_manual() {
            eprintln!(
                "  fan '{}': cannot set manual mode ({}), skipping",
                fan.name, e
            );
            controllable.push(false);
            continue;
        }
        match write_pwm_safe(fan, 128) {
            Ok(_) => controllable.push(true),
            Err(_) => {
                eprintln!(
                    "  fan '{}': driver rejects PWM writes, skipping (firmware-controlled?)",
                    fan.name
                );
                controllable.push(false);
            }
        }
    }

    let n_controllable = controllable.iter().filter(|&&c| c).count();
    if n_controllable == 0 {
        anyhow::bail!("no fans are controllable — cannot benchmark");
    }
    eprintln!("{}/{} fans controllable", n_controllable, fans.len());

    // ── Pre-flight: stall detection ─────────────────────────────────────────

    eprintln!("\n=== Stall detection ===");
    let mut stall_thresholds: std::collections::HashMap<String, u8> =
        std::collections::HashMap::new();
    for (fan, &is_ctrl) in fans.iter_mut().zip(controllable.iter()) {
        interrupt.check()?;
        if !is_ctrl {
            eprintln!("  {} ... skipped (not controllable)", fan.name);
            continue;
        }
        eprint!("  {} ... ", fan.name);
        let stall = find_stall_threshold(fan, &interrupt)?;
        eprintln!("stall PWM = {}", stall);
        stall_thresholds.insert(fan.name.clone(), stall);
        write_pwm_safe(fan, 0)?;
    }

    // ── Idle baseline ───────────────────────────────────────────────────────

    eprintln!("\n=== Idle baseline (all fans max) ===");
    for (fan, &is_ctrl) in fans.iter_mut().zip(controllable.iter()) {
        if is_ctrl {
            write_pwm_safe(fan, 255)?;
        }
    }
    wait_for_settle(sensors, &vec![true; sensors.len()], &interrupt)?;
    let baseline = sample_temps(sensors, 3, &interrupt)?;
    eprintln!("Baseline temperatures (full cooling):");
    for (i, name) in sensor_names.iter().enumerate() {
        eprintln!("  {} = {:.1}°C", name, baseline[i]);
    }

    // ── Stress phases ───────────────────────────────────────────────────────

    let mut all_measurements: Vec<PhaseMeasurement> = Vec::new();

    if has_cpu_sensors {
        eprintln!("\n=== CPU Stress Phase ===");
        let phase_measurements = run_stress_phase(
            fans,
            sensors,
            sensor_names,
            &classified,
            &controllable,
            &stall_thresholds,
            &baseline,
            &interrupt,
            "cpu",
            StressProcess::start_cpu,
        )?;
        all_measurements.extend(phase_measurements);
    }

    if has_gpu_sensors {
        eprintln!("\n=== GPU Stress Phase ===");
        let phase_measurements = run_stress_phase(
            fans,
            sensors,
            sensor_names,
            &classified,
            &controllable,
            &stall_thresholds,
            &baseline,
            &interrupt,
            "gpu",
            StressProcess::start_gpu,
        )?;
        all_measurements.extend(phase_measurements);
    }

    // ── Compute coupling matrix ─────────────────────────────────────────────

    let tuning = compute_tuning(&all_measurements, &classified, sensor_names);
    eprintln!(
        "\nBenchmark complete. {} coupling entries.",
        tuning.coupling_matrix.len()
    );
    let uncontrollable = fans
        .iter()
        .zip(&controllable)
        .filter(|(_, ok)| !**ok)
        .map(|(fan, _)| fan.name.clone())
        .collect();
    control
        .restore()
        .context("failed to restore fan control after benchmark")?;

    Ok((tuning, uncontrollable))
}

/// Run a single stress phase (CPU or GPU):
/// 1. Start stress workload
/// 2. Wait for target sensors to warm up
/// 3. Sweep each fan through PWM levels, measuring sensor temps
/// 4. Stop stress
#[allow(clippy::too_many_arguments)]
fn run_stress_phase<F>(
    fans: &mut [Fan],
    sensors: &[Sensor],
    sensor_names: &[String],
    classified: &[ClassifiedFan],
    controllable: &[bool],
    stall_thresholds: &std::collections::HashMap<String, u8>,
    baseline: &[f64],
    interrupt: &InterruptGuard,
    target_prefix: &str,
    start_stress: F,
) -> Result<Vec<PhaseMeasurement>>
where
    F: FnOnce() -> Result<StressProcess>,
{
    // Start stress workload
    let mut stress = start_stress()?;

    // Set all controllable fans to max during warmup so temps rise from workload, not fans
    for (fan, &is_ctrl) in fans.iter_mut().zip(controllable.iter()) {
        if is_ctrl {
            write_pwm_safe(fan, 255)?;
        }
    }

    // Wait for target temps to rise
    eprintln!("  Waiting for {} temps to rise...", target_prefix);
    wait_for_stress_warmup(
        sensors,
        sensor_names,
        target_prefix,
        baseline,
        5.0,
        interrupt,
    )?;

    // Sample stressed baseline (at max fan speed)
    let stressed_baseline = sample_temps(sensors, 3, interrupt)?;
    eprintln!("  Stressed temperatures (fans at max):");
    for (i, name) in sensor_names.iter().enumerate() {
        if name.starts_with(target_prefix) {
            eprintln!(
                "    {} = {:.1}°C (+{:.1}°C from idle)",
                name,
                stressed_baseline[i],
                stressed_baseline[i] - baseline[i]
            );
        }
    }

    // Sweep each fan while stress continues
    let mut measurements = Vec::new();

    for (fan_idx, cf) in classified.iter().enumerate() {
        interrupt.check()?;
        if !controllable[fan_idx] {
            continue;
        }

        if let FanRole::CaseFollower { .. } = cf.role {
            continue;
        }

        eprintln!(
            "\n  --- Sweeping: {} ({:?}) under {} stress ---",
            cf.name, cf.role, target_prefix
        );

        // Set all OTHER fans to max cooling so only the swept fan's effect is measured
        for (i, fan) in fans.iter_mut().enumerate() {
            if i != fan_idx && controllable[i] {
                write_pwm_safe(fan, 255)?;
            }
        }

        let stall = *stall_thresholds.get(&cf.name).unwrap_or(&0);
        let mut readings = Vec::new();

        let mut levels: Vec<u8> = PWM_LEVELS.iter().copied().filter(|&p| p > stall).collect();
        levels.insert(0, stall.max(1));
        let effective_levels = sweep_order(levels);
        let watch: Vec<bool> = sensor_names
            .iter()
            .map(|n| n.starts_with(target_prefix))
            .collect();
        let sweep_start = std::time::Instant::now();

        for &pwm in &effective_levels {
            interrupt.check()?;
            eprint!("    PWM={:>3} ... ", pwm);
            let pwm = write_pwm_safe(&mut fans[fan_idx], pwm)?;

            wait_for_settle(sensors, &watch, interrupt)?;

            // Time at the middle of the sampling window, for the drift term.
            let t_mid = sweep_start.elapsed().as_secs_f64() + STRESS_SAMPLE_SECS as f64 / 2.0;
            let temps = sample_temps(sensors, STRESS_SAMPLE_SECS, interrupt)?;

            // Print only target sensors
            let temp_str: Vec<String> = sensor_names
                .iter()
                .zip(temps.iter())
                .filter(|(name, _)| name.starts_with(target_prefix))
                .map(|(name, t)| format!("{}={:.1}°C", name, t))
                .collect();
            eprintln!("{}", temp_str.join(", "));

            readings.push((pwm, t_mid, temps));
        }

        // Restore to max cooling before next fan
        write_pwm_safe(&mut fans[fan_idx], 255)?;

        measurements.push(PhaseMeasurement {
            fan_name: cf.name.clone(),
            readings,
        });
    }

    // Stop stress
    stress.stop().context("failed to stop stress workload")?;

    // Brief cooldown
    eprintln!("  Cooling down...");
    for (fan, &is_ctrl) in fans.iter_mut().zip(controllable.iter()) {
        if is_ctrl {
            write_pwm_safe(fan, 255)?;
        }
    }
    interrupt.sleep(Duration::from_secs(10))?;

    Ok(measurements)
}

/// Compute thermal coupling from stress benchmark measurements.
///
/// For each fan×sensor pair, fits `temp = a + b·pwm + c·t` by OLS, where `t`
/// is elapsed sweep time; the drift term absorbs residual heat soak that the
/// interleaved sweep order makes separable from the fan effect. A coupling is
/// kept only when `b` differs from zero at the 95% level. When a pair is
/// measured in several stress phases, the most precise (smallest standard
/// error) estimate wins; picking the largest |beta| would select noise.
/// Negative beta = fan cools that sensor. Positive beta = fan heats it.
/// Group followers inherit their representative's data.
fn compute_tuning(
    measurements: &[PhaseMeasurement],
    classified: &[ClassifiedFan],
    sensor_names: &[String],
) -> TuningResponse {
    // (fan, sensor) -> (beta, se(beta), r², dof); beta and se in °C per +10 PWM.
    type Estimate = (f64, f64, f64, usize);
    let mut best_coupling: std::collections::BTreeMap<(String, String), Estimate> =
        std::collections::BTreeMap::new();

    for measurement in measurements {
        let x: Vec<Vec<f64>> = measurement
            .readings
            .iter()
            .map(|(pwm, t, _)| vec![1.0, *pwm as f64, *t])
            .collect();
        for (sensor_idx, sensor_name) in sensor_names.iter().enumerate() {
            let y: Vec<f64> = measurement
                .readings
                .iter()
                .map(|(_, _, temps)| temps[sensor_idx])
                .collect();
            let Some(fit) = ols(&x, &y) else {
                continue;
            };
            let se = fit.se[1] * 10.0;
            if !se.is_finite() {
                continue;
            }
            let key = (measurement.fan_name.clone(), sensor_name.clone());
            if best_coupling
                .get(&key)
                .is_none_or(|(_, prev_se, _, _)| se < *prev_se)
            {
                best_coupling.insert(key, (fit.coef[1] * 10.0, se, fit.r_squared, fit.dof));
            }
        }
    }

    // Test significance only on the selected (most precise) estimate.
    let mut coupling_matrix: Vec<CouplingEntry> = best_coupling
        .into_iter()
        .filter(|(_, (beta, se, _, dof))| *beta != 0.0 && beta.abs() > t_critical_95(*dof) * se)
        .map(|((fan, sensor), (beta, _, r_squared, _))| CouplingEntry {
            fan,
            sensor,
            beta,
            r_squared,
        })
        .collect();

    // Propagate to group followers
    for cf in classified {
        if let FanRole::CaseFollower { ref representative } = cf.role {
            let rep_entries: Vec<CouplingEntry> = coupling_matrix
                .iter()
                .filter(|e| e.fan == *representative)
                .map(|e| CouplingEntry {
                    fan: cf.name.clone(),
                    ..e.clone()
                })
                .collect();
            coupling_matrix.extend(rep_entries);
        }
    }

    TuningResponse {
        coupling_matrix,
        // A steady-state sweep identifies static gains only; time constants
        // come from the daemon's online step-response fitter.
        step_responses: Vec::new(),
        cross_correlations: Vec::new(),
        thermal_integrals: Vec::new(),
    }
}

struct OlsFit {
    coef: Vec<f64>,
    se: Vec<f64>,
    r_squared: f64,
    dof: usize,
}

/// Ordinary least squares via the normal equations (fine for p ≤ 3).
/// Returns `None` when the design is singular or has no residual degrees
/// of freedom.
fn ols(x: &[Vec<f64>], y: &[f64]) -> Option<OlsFit> {
    let n = y.len();
    let p = x.first()?.len();
    if n <= p {
        return None;
    }
    // Augmented [XᵀX | I] for Gauss-Jordan inversion.
    let mut m = vec![vec![0.0; 2 * p]; p];
    for (i, row) in m.iter_mut().enumerate() {
        for j in 0..p {
            row[j] = x.iter().map(|r| r[i] * r[j]).sum();
        }
        row[p + i] = 1.0;
    }
    for col in 0..p {
        let pivot = (col..p).max_by(|&a, &b| m[a][col].abs().total_cmp(&m[b][col].abs()))?;
        let scale = m.iter().map(|r| r[col].abs()).fold(0.0, f64::max);
        if m[pivot][col].abs() <= 1e-10 * scale.max(1.0) {
            return None;
        }
        m.swap(col, pivot);
        let d = m[col][col];
        m[col].iter_mut().for_each(|v| *v /= d);
        for r in 0..p {
            if r != col {
                let f = m[r][col];
                let pivot_row = m[col].clone();
                m[r].iter_mut()
                    .zip(pivot_row)
                    .for_each(|(v, pv)| *v -= f * pv);
            }
        }
    }
    let inv: Vec<&[f64]> = m.iter().map(|r| &r[p..]).collect();
    let xty: Vec<f64> = (0..p)
        .map(|j| x.iter().zip(y).map(|(r, yi)| r[j] * yi).sum())
        .collect();
    let coef: Vec<f64> = (0..p)
        .map(|i| (0..p).map(|j| inv[i][j] * xty[j]).sum())
        .collect();

    let ss_res: f64 = x
        .iter()
        .zip(y)
        .map(|(r, yi)| (yi - r.iter().zip(&coef).map(|(a, b)| a * b).sum::<f64>()).powi(2))
        .sum();
    let y_mean = y.iter().sum::<f64>() / n as f64;
    let ss_tot: f64 = y.iter().map(|yi| (yi - y_mean).powi(2)).sum();
    let dof = n - p;
    let sigma2 = ss_res / dof as f64;
    Some(OlsFit {
        se: (0..p)
            .map(|i| (sigma2 * inv[i][i]).max(0.0).sqrt())
            .collect(),
        coef,
        r_squared: if ss_tot > 1e-12 {
            1.0 - ss_res / ss_tot
        } else {
            0.0
        },
        dof,
    })
}

/// Two-sided 95% Student-t critical value.
fn t_critical_95(dof: usize) -> f64 {
    const TABLE: [f64; 10] = [
        12.706, 4.303, 3.182, 2.776, 2.571, 2.447, 2.365, 2.306, 2.262, 2.228,
    ];
    match dof {
        0 => f64::INFINITY,
        1..=10 => TABLE[dof - 1],
        11..=20 => 2.086,
        21..=40 => 2.021,
        _ => 1.96,
    }
}

#[cfg(test)]
mod stats_tests {
    use super::*;

    #[test]
    fn sweep_order_interleaves_and_repeats_reference() {
        assert_eq!(
            sweep_order(vec![30, 40, 100, 180, 255]),
            vec![255, 30, 180, 40, 100, 255]
        );
    }

    #[test]
    fn drift_is_not_mistaken_for_fan_effect() {
        let classified = vec![ClassifiedFan {
            name: "fan".into(),
            role: FanRole::DirectCooler,
        }];
        let names = vec!["cpu".to_string(), "drift_only".to_string()];
        // True model: cpu cools 0.5 °C per +10 PWM; both sensors heat-soak
        // at 0.02 °C/s; small deterministic "noise".
        let noise = [0.05, -0.04, 0.03, -0.05, 0.04, -0.03];
        let readings = sweep_order(vec![30, 40, 100, 180, 255])
            .into_iter()
            .enumerate()
            .map(|(i, pwm)| {
                let t = 60.0 * i as f64;
                let soak = 0.02 * t + noise[i];
                (pwm, t, vec![90.0 - 0.05 * pwm as f64 + soak, 60.0 + soak])
            })
            .collect();
        let tuning = compute_tuning(
            &[PhaseMeasurement {
                fan_name: "fan".into(),
                readings,
            }],
            &classified,
            &names,
        );

        assert_eq!(
            tuning.coupling_matrix.len(),
            1,
            "{:?}",
            tuning.coupling_matrix
        );
        let entry = &tuning.coupling_matrix[0];
        assert_eq!(entry.sensor, "cpu");
        assert!((entry.beta + 0.5).abs() < 0.05, "beta = {}", entry.beta);
        assert!(tuning.step_responses.is_empty());
    }

    #[test]
    fn precise_null_phase_overrides_noisy_significant_phase() {
        let classified = vec![ClassifiedFan {
            name: "fan".into(),
            role: FanRole::DirectCooler,
        }];
        let names = vec!["board".to_string()];
        let phase = |slope: f64, noise: [f64; 6]| PhaseMeasurement {
            fan_name: "fan".into(),
            readings: sweep_order(vec![30, 40, 100, 180, 255])
                .into_iter()
                .enumerate()
                .map(|(i, pwm)| {
                    (
                        pwm,
                        60.0 * i as f64,
                        vec![50.0 + slope * pwm as f64 + noise[i]],
                    )
                })
                .collect(),
        };
        // Noisy phase: significant cooling on its own. Precise phase: no effect.
        let noisy = phase(-0.05, [0.4, -0.3, 0.2, -0.4, 0.3, -0.2]);
        let precise = phase(0.0, [0.01, -0.01, 0.005, -0.01, 0.01, -0.005]);
        let alone = compute_tuning(std::slice::from_ref(&noisy), &classified, &names);
        assert_eq!(alone.coupling_matrix.len(), 1);
        let tuning = compute_tuning(&[noisy, precise], &classified, &names);
        assert!(
            tuning.coupling_matrix.is_empty(),
            "{:?}",
            tuning.coupling_matrix
        );
    }
}
